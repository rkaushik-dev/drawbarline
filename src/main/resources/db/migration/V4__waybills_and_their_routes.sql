-- Waybills and the routes they are authorised over, one row a station in the order it is passed.

CREATE TABLE waybill (
    number INTEGER NOT NULL,
    dated DATE NOT NULL,
    car_mark CHARACTER VARYING(11) NOT NULL,
    shipper CHARACTER VARYING(60) NOT NULL,
    consignee CHARACTER VARYING(60) NOT NULL,
    lading_stcc CHARACTER VARYING(7),
    lading_name CHARACTER VARYING(60),
    lading_pounds BIGINT,
    lading_bulk BOOLEAN NOT NULL,
    CONSTRAINT pk_waybill PRIMARY KEY (number),
    CONSTRAINT ck_waybill_numbered_from_one CHECK (number >= 1),
    CONSTRAINT ck_waybill_lading_weighs CHECK (lading_stcc is null or lading_pounds > 0)
);
CREATE INDEX ix_waybill_car_mark ON waybill (car_mark);
CREATE INDEX ix_waybill_dated ON waybill (dated);

CREATE TABLE route_stop (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    waybill_number INTEGER NOT NULL,
    position INTEGER NOT NULL,
    station CHARACTER VARYING(4) NOT NULL,
    CONSTRAINT pk_route_stop PRIMARY KEY (id),
    CONSTRAINT uq_stop_one_a_position UNIQUE (waybill_number, position),
    CONSTRAINT ck_stop_position_not_negative CHECK (position >= 0)
);
CREATE INDEX ix_route_stop_waybill_number ON route_stop (waybill_number);

ALTER TABLE waybill ADD CONSTRAINT fk_waybill_car_mark_car
    FOREIGN KEY (car_mark) REFERENCES car (mark) ON DELETE RESTRICT;
ALTER TABLE route_stop ADD CONSTRAINT fk_route_stop_waybill_number_waybill
    FOREIGN KEY (waybill_number) REFERENCES waybill (number) ON DELETE CASCADE;
