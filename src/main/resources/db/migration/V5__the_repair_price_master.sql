-- The repair price master: priced jobs by date, depreciation by family of parts, and what each
-- road charges an hour.

CREATE TABLE depreciation (
    family CHARACTER VARYING(2) NOT NULL,
    percent_a_year INTEGER NOT NULL,
    floor_percent INTEGER NOT NULL,
    CONSTRAINT pk_depreciation PRIMARY KEY (family),
    CONSTRAINT ck_depreciation_is_a_percentage CHECK (percent_a_year between 0 and 100),
    CONSTRAINT ck_depreciation_floor CHECK (floor_percent between 0 and 100)
);

CREATE TABLE labor_rate (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    road CHARACTER VARYING(4) NOT NULL,
    effective DATE NOT NULL,
    cents_an_hour INTEGER NOT NULL,
    CONSTRAINT pk_labor_rate PRIMARY KEY (id),
    CONSTRAINT uq_labor_one_a_day UNIQUE (road, effective),
    CONSTRAINT ck_labor_not_negative CHECK (cents_an_hour >= 0)
);
CREATE INDEX ix_labor_rate_road ON labor_rate (road);

CREATE TABLE price_line (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    job CHARACTER VARYING(4) NOT NULL,
    effective DATE NOT NULL,
    labor_hundredths INTEGER NOT NULL,
    material_cents INTEGER NOT NULL,
    CONSTRAINT pk_price_line PRIMARY KEY (id),
    CONSTRAINT uq_price_one_a_day UNIQUE (job, effective),
    CONSTRAINT ck_price_labor_not_negative CHECK (labor_hundredths >= 0),
    CONSTRAINT ck_price_material_not_negative CHECK (material_cents >= 0)
);
CREATE INDEX ix_price_line_job ON price_line (job);
