-- Repair cards and their lines, the exceptions filed against those lines, and how each exception
-- was answered. All four tables are written once and never edited.

CREATE TABLE repair_card (
    number INTEGER NOT NULL,
    car_mark CHARACTER VARYING(11) NOT NULL,
    performed_by CHARACTER VARYING(4) NOT NULL,
    performed_on DATE NOT NULL,
    station CHARACTER VARYING(4) NOT NULL,
    CONSTRAINT pk_repair_card PRIMARY KEY (number),
    CONSTRAINT ck_card_numbered_from_one CHECK (number >= 1)
);
CREATE INDEX ix_repair_card_car_mark ON repair_card (car_mark);
CREATE INDEX ix_repair_card_performed_by ON repair_card (performed_by);
CREATE INDEX ix_repair_card_performed_on ON repair_card (performed_on);

CREATE TABLE defect (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    card_number INTEGER NOT NULL,
    position INTEGER NOT NULL,
    job CHARACTER VARYING(4) NOT NULL,
    why_made CHARACTER VARYING(2) NOT NULL,
    quantity INTEGER NOT NULL,
    overridden CHARACTER VARYING(16),
    part_years INTEGER NOT NULL,
    note CHARACTER VARYING(120) NOT NULL,
    CONSTRAINT pk_defect PRIMARY KEY (id),
    CONSTRAINT uq_defect_one_a_position UNIQUE (card_number, position),
    CONSTRAINT ck_defect_covers_a_part CHECK (quantity >= 1),
    CONSTRAINT ck_defect_part_age CHECK (part_years >= 0)
);
CREATE INDEX ix_defect_card_number ON defect (card_number);

CREATE TABLE objection (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    card_number INTEGER NOT NULL,
    line INTEGER NOT NULL,
    ground CHARACTER VARYING(20) NOT NULL,
    disputed BIGINT NOT NULL,
    filed_on DATE NOT NULL,
    note CHARACTER VARYING(200) NOT NULL,
    CONSTRAINT pk_objection PRIMARY KEY (id),
    CONSTRAINT uq_objection_one_a_line UNIQUE (card_number, line),
    CONSTRAINT ck_objection_disputes_something CHECK (disputed > 0)
);
CREATE INDEX ix_objection_card_number ON objection (card_number);

CREATE TABLE resolution (
    objection_id INTEGER NOT NULL,
    outcome CHARACTER VARYING(16) NOT NULL,
    allowed BIGINT NOT NULL,
    CONSTRAINT pk_resolution PRIMARY KEY (objection_id),
    CONSTRAINT ck_resolution_not_negative CHECK (allowed >= 0)
);

ALTER TABLE repair_card ADD CONSTRAINT fk_repair_card_car_mark_car
    FOREIGN KEY (car_mark) REFERENCES car (mark) ON DELETE RESTRICT;
ALTER TABLE defect ADD CONSTRAINT fk_defect_card_number_repair_card
    FOREIGN KEY (card_number) REFERENCES repair_card (number) ON DELETE CASCADE;
ALTER TABLE objection ADD CONSTRAINT fk_objection_card_number_repair_card
    FOREIGN KEY (card_number) REFERENCES repair_card (number) ON DELETE CASCADE;
ALTER TABLE resolution ADD CONSTRAINT fk_resolution_objection_id_objection
    FOREIGN KEY (objection_id) REFERENCES objection (id) ON DELETE CASCADE;
