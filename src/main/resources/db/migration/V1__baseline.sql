-- The schema as it stands at the first release: the fleet, car hire rates, the ledger and its
-- months, the document counters and the event log.
--
-- Tables first, then their indexes, then the foreign keys, so every foreign key finds the index
-- that already covers its column rather than having one made for it.

CREATE TABLE car (
    mark CHARACTER VARYING(11) NOT NULL,
    owner CHARACTER VARYING(4) NOT NULL,
    designation CHARACTER VARYING(4) NOT NULL,
    type_code CHARACTER VARYING(4) NOT NULL,
    built DATE NOT NULL,
    rebuilt DATE,
    light_weight BIGINT NOT NULL,
    gross_rail_load BIGINT NOT NULL,
    outside_length INTEGER NOT NULL,
    CONSTRAINT pk_car PRIMARY KEY (mark),
    CONSTRAINT ck_car_light_under_gross CHECK (light_weight < gross_rail_load),
    CONSTRAINT ck_car_has_length CHECK (outside_length > 0)
);
CREATE INDEX ix_car_owner ON car (owner);
CREATE INDEX ix_car_type_code ON car (type_code);

CREATE TABLE car_hire_band (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type_code CHARACTER VARYING(4) NOT NULL,
    from_age INTEGER NOT NULL,
    to_age INTEGER NOT NULL,
    effective DATE NOT NULL,
    hourly_tenths INTEGER NOT NULL,
    mileage_mills INTEGER NOT NULL,
    CONSTRAINT pk_car_hire_band PRIMARY KEY (id),
    CONSTRAINT uq_band_not_filed_twice UNIQUE (type_code, from_age, effective),
    CONSTRAINT ck_band_age_from_zero CHECK (from_age >= 0),
    CONSTRAINT ck_band_age_climbs CHECK (to_age >= from_age),
    CONSTRAINT ck_band_hourly_not_negative CHECK (hourly_tenths >= 0),
    CONSTRAINT ck_band_mileage_not_negative CHECK (mileage_mills >= 0)
);
CREATE INDEX ix_band_lookup ON car_hire_band (type_code, effective);

CREATE TABLE closed_period (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    period_year INTEGER NOT NULL,
    period_month INTEGER NOT NULL,
    closed_on DATE NOT NULL,
    CONSTRAINT pk_closed_period PRIMARY KEY (id),
    CONSTRAINT uq_closed_once UNIQUE (period_year, period_month),
    CONSTRAINT ck_closed_month CHECK (period_month between 1 and 12)
);

CREATE TABLE counter (
    name CHARACTER VARYING(24) NOT NULL,
    next_number INTEGER NOT NULL,
    CONSTRAINT pk_counter PRIMARY KEY (name),
    CONSTRAINT ck_counter_numbered_from_one CHECK (next_number >= 1)
);

CREATE TABLE posting (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    road CHARACTER VARYING(4) NOT NULL,
    period_year INTEGER NOT NULL,
    period_month INTEGER NOT NULL,
    kind CHARACTER VARYING(12) NOT NULL,
    amount BIGINT NOT NULL,
    posted_on DATE NOT NULL,
    reference CHARACTER VARYING(60) NOT NULL,
    CONSTRAINT pk_posting PRIMARY KEY (id),
    CONSTRAINT ck_posting_month CHECK (period_month between 1 and 12)
);
CREATE INDEX ix_posting_road ON posting (road);
CREATE INDEX ix_posting_road_period ON posting (road, period_year, period_month);

CREATE TABLE reopening (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    period_year INTEGER NOT NULL,
    period_month INTEGER NOT NULL,
    reopened_on DATE NOT NULL,
    reason CHARACTER VARYING(200) NOT NULL,
    CONSTRAINT pk_reopening PRIMARY KEY (id),
    CONSTRAINT ck_reopening_month CHECK (period_month between 1 and 12)
);

CREATE TABLE car_event (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    car_mark CHARACTER VARYING(11) NOT NULL,
    kind CHARACTER VARYING(16) NOT NULL,
    happened TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    station CHARACTER VARYING(4) NOT NULL,
    road CHARACTER VARYING(4),
    industry CHARACTER VARYING(12),
    waybill INTEGER,
    tenths INTEGER,
    note CHARACTER VARYING(120) NOT NULL,
    CONSTRAINT pk_car_event PRIMARY KEY (id),
    CONSTRAINT uq_event_not_twice UNIQUE (car_mark, kind, happened, station),
    CONSTRAINT ck_event_movement_covers_ground CHECK (tenths is null or tenths > 0),
    CONSTRAINT ck_event_waybill_numbered CHECK (waybill is null or waybill > 0)
);
CREATE INDEX ix_car_event_car_mark ON car_event (car_mark);
CREATE INDEX ix_event_car_when ON car_event (car_mark, happened);
CREATE INDEX ix_event_when ON car_event (happened);

CREATE TABLE lease (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    car_mark CHARACTER VARYING(11) NOT NULL,
    lessee CHARACTER VARYING(4) NOT NULL,
    began DATE NOT NULL,
    ended DATE,
    CONSTRAINT pk_lease PRIMARY KEY (id),
    CONSTRAINT uq_lease_one_start_a_day UNIQUE (car_mark, began),
    CONSTRAINT ck_lease_ends_after CHECK (ended is null or ended >= began)
);
CREATE INDEX ix_lease_car_mark ON lease (car_mark);
CREATE INDEX ix_lease_lessee ON lease (lessee);

CREATE TABLE retirement (
    car_mark CHARACTER VARYING(11) NOT NULL,
    "ON" DATE NOT NULL,
    reason CHARACTER VARYING(120) NOT NULL,
    CONSTRAINT pk_retirement PRIMARY KEY (car_mark)
);

ALTER TABLE car_event ADD CONSTRAINT fk_car_event_car_mark_car
    FOREIGN KEY (car_mark) REFERENCES car (mark) ON DELETE RESTRICT;
ALTER TABLE lease ADD CONSTRAINT fk_lease_car_mark_car
    FOREIGN KEY (car_mark) REFERENCES car (mark) ON DELETE CASCADE;
ALTER TABLE retirement ADD CONSTRAINT fk_retirement_car_mark_car
    FOREIGN KEY (car_mark) REFERENCES car (mark) ON DELETE CASCADE;
