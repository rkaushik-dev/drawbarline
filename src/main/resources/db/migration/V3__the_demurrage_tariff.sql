-- The demurrage tariff: published schedules and their steps, and the average agreements signed
-- with one shipper at a time.

CREATE TABLE tariff (
    code CHARACTER VARYING(8) NOT NULL,
    effective DATE NOT NULL,
    free_days_loaded INTEGER NOT NULL,
    free_days_empty INTEGER NOT NULL,
    CONSTRAINT pk_tariff PRIMARY KEY (code),
    CONSTRAINT uq_tariff_one_a_day UNIQUE (effective),
    CONSTRAINT ck_tariff_loaded_free_time CHECK (free_days_loaded >= 0),
    CONSTRAINT ck_tariff_empty_free_time CHECK (free_days_empty >= 0)
);

CREATE TABLE average_agreement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    shipper_code CHARACTER VARYING(8) NOT NULL,
    daily_cents INTEGER NOT NULL,
    effective DATE NOT NULL,
    expires DATE,
    CONSTRAINT pk_average_agreement PRIMARY KEY (id),
    CONSTRAINT uq_agreement_one_a_day UNIQUE (shipper_code, effective),
    CONSTRAINT ck_agreement_not_negative CHECK (daily_cents >= 0),
    CONSTRAINT ck_agreement_ends_after CHECK (expires is null or expires >= effective)
);
CREATE INDEX ix_average_agreement_shipper_code ON average_agreement (shipper_code);

CREATE TABLE tariff_step (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tariff_code CHARACTER VARYING(8) NOT NULL,
    position INTEGER NOT NULL,
    through INTEGER NOT NULL,
    cents INTEGER NOT NULL,
    CONSTRAINT pk_tariff_step PRIMARY KEY (id),
    CONSTRAINT uq_step_one_a_position UNIQUE (tariff_code, position),
    CONSTRAINT ck_step_through_not_negative CHECK (through >= 0),
    CONSTRAINT ck_step_not_negative CHECK (cents >= 0)
);
CREATE INDEX ix_tariff_step_tariff_code ON tariff_step (tariff_code);

ALTER TABLE average_agreement ADD CONSTRAINT fk_average_agreement_shipper_code_shipper
    FOREIGN KEY (shipper_code) REFERENCES shipper (code) ON DELETE CASCADE;
ALTER TABLE tariff_step ADD CONSTRAINT fk_tariff_step_tariff_code_tariff
    FOREIGN KEY (tariff_code) REFERENCES tariff (code) ON DELETE CASCADE;
