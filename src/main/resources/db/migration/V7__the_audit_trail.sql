-- The audit trail: one row a decision somebody made, and nothing else.

CREATE TABLE audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor CHARACTER VARYING(32) NOT NULL,
    action CHARACTER VARYING(24) NOT NULL,
    subject CHARACTER VARYING(60) NOT NULL,
    detail CHARACTER VARYING(200) NOT NULL,
    CONSTRAINT pk_audit PRIMARY KEY (id)
);
CREATE INDEX ix_audit_action ON audit (action);
CREATE INDEX ix_audit_actor_at ON audit (actor, at);
CREATE INDEX ix_audit_at ON audit (at);
CREATE INDEX ix_audit_subject ON audit (subject);
