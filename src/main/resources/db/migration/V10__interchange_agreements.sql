-- Interchange agreements: what one road takes at one junction, from a date.
--
-- Constraint names are unique across the schema, and the average agreement table already holds
-- the plain names for one agreement a day and an end after the start, so these two carry the
-- table's name.

CREATE TABLE interchange_agreement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    road CHARACTER VARYING(4) NOT NULL,
    junction CHARACTER VARYING(4) NOT NULL,
    effective DATE NOT NULL,
    kinds CHARACTER VARYING(16) NOT NULL,
    daily_cap INTEGER NOT NULL,
    opens TIME(6) NOT NULL,
    closes TIME(6) NOT NULL,
    hazardous BOOLEAN NOT NULL,
    expires DATE,
    CONSTRAINT pk_interchange_agreement PRIMARY KEY (id),
    CONSTRAINT uq_interchange_agreement_one_a_day UNIQUE (road, junction, effective),
    CONSTRAINT ck_agreement_takes_a_car CHECK (daily_cap >= 1),
    CONSTRAINT ck_agreement_takes_a_kind CHECK (length(kinds) > 0),
    CONSTRAINT ck_agreement_opens_first CHECK (opens < closes),
    CONSTRAINT ck_interchange_agreement_ends_after CHECK (expires is null or expires >= effective)
);
CREATE INDEX ix_agreement_junction ON interchange_agreement (junction, effective);
CREATE INDEX ix_interchange_agreement_road ON interchange_agreement (road);
